"""A generated findings report (PDF) for one submission.

Used for DOCX files, whose pages are not rendered by the scanner, so source-accurate
annotations cannot be verified. The report is clearly labelled as generated: it is not a
copy of the submission and claims no page coordinates for DOCX findings.
"""

from __future__ import annotations

import io
import os
from html import escape
from pathlib import Path

import pymupdf

from pps_ats.reports.annotate import STYLES, score_effects
from pps_ats.schemas.batch import AnnotationReport
from pps_ats.schemas.findings import AnalysisResult, FindingClass
from pps_ats.schemas.scoring import ScoringResult

CSS = """
* { font-family: sans-serif; }
body { font-size: 9.5pt; }
h1 { font-size: 15pt; margin-bottom: 2pt; }
h2 { font-size: 12pt; margin-top: 10pt; border-bottom: 1px solid #999; }
.meta { color: #555; font-size: 8.5pt; }
.f { margin: 0 0 7pt 0; padding-left: 6pt; border-left: 3px solid #aaa; }
.r { font-weight: bold; }
.t { font-family: monospace; background-color: #f2f2f2; }
.definite_defect { border-left-color: #e05050; }
.potential_issue { border-left-color: #f08000; }
.recommendation { border-left-color: #2a66f0; }
td, th { padding: 1pt 6pt 1pt 0; text-align: left; }
"""


def _marks_html(scoring: ScoringResult) -> str:
    if scoring.ca1 is None:
        return f"<p><b>No marks</b> ({escape(scoring.status.value)}).</p>"
    rows = "".join(
        f"<tr><td>{escape(c.label)}</td><td>{c.final_score:g} / {c.max_points:g}</td>"
        f"<td>{escape(c.band.value)}</td></tr>"
        for c in scoring.ca1.criteria
    )
    ats = f"{scoring.ats.score:g} / 100 ({scoring.ats.band})" if scoring.ats else "n/a"
    return (
        f"<table>{rows}<tr><th>Total</th><th>{scoring.ca1.total:g} / "
        f"{scoring.ca1.max_total:g}</th><th>{escape(scoring.status.value)}</th></tr></table>"
        f"<p>ATS compatibility (separate from CA1): {escape(ats)}</p>"
    )


def build_html(
    analysis: AnalysisResult,
    scoring: ScoringResult,
    annotation: AnnotationReport | None = None,
    display_name: str | None = None,
) -> str:
    doc = analysis.document
    effects = score_effects(scoring)
    parts = [
        "<h1>Resume findings report</h1>",
        f"<p class='meta'>{escape(display_name or doc.file_name)} &middot; "
        f"sha256 {doc.sha256[:16]}&hellip; &middot; generated {escape(scoring.generated_at)}"
        "<br/>Generated by the PPS ATS scanner. This is not a copy of the submission. "
        "Marks are provisional until reviewed by faculty.</p>",
    ]
    if doc.detected_format.value == "docx":
        parts.append(
            "<p class='meta'>DOCX: the scanner does not render Word pages, so findings are "
            "listed by section and text rather than marked on a page.</p>"
        )
    parts.append(_marks_html(scoring))
    if scoring.review_reasons:
        items = "".join(f"<li>{escape(r)}</li>" for r in scoring.review_reasons)
        parts.append(f"<h2>Manual review</h2><ul>{items}</ul>")
    for cls in FindingClass:
        group = [f for f in analysis.findings if f.finding_class is cls]
        if not group:
            continue
        parts.append(f"<h2>{escape(STYLES[cls][2])}s ({len(group)})</h2>")
        for f in group:
            where = []
            if f.section:
                where.append(f"section: {escape(f.section)}")
            if f.page_number:
                where.append(f"page {f.page_number}")
            if annotation is not None:
                where.append(f"annotation: {annotation.status_for(f.issue_id).value}")
            text = (
                f"<br/>Text: <span class='t'>{escape(f.detected_text)}</span>"
                if (f.detected_text)
                else ""
            )
            fix = (
                f"<br/>Suggestion: {escape(f.suggested_correction)}"
                if f.suggested_correction
                else ""
            )
            parts.append(
                f"<div class='f {cls.value}'><span class='r'>{escape(f.rule_id)}</span> "
                f"&middot; {escape(f.severity.value)} &middot; {escape(f.rubric_criterion.value)}"
                f"<br/>{escape(f.explanation)}{text}{fix}"
                f"<br/><span class='meta'>{' &middot; '.join(where)} &middot; CA1 effect: "
                f"{escape(effects.get(f.issue_id, 'not part of CA1 marks'))}</span></div>"
            )
    if not analysis.findings:
        parts.append("<p>No findings.</p>")
    return "<body>" + "".join(parts) + "</body>"


def write_findings_report(
    analysis: AnalysisResult,
    scoring: ScoringResult,
    output: str | Path,
    annotation: AnnotationReport | None = None,
    display_name: str | None = None,
) -> Path:
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_name(output.name + ".part")
    story = pymupdf.Story(
        html=build_html(analysis, scoring, annotation, display_name), user_css=CSS
    )
    buffer = io.BytesIO()  # a file path would stay locked on Windows until GC
    writer = pymupdf.DocumentWriter(buffer)
    mediabox = pymupdf.paper_rect("a4")
    where = mediabox + (40, 40, -40, -40)
    more = 1
    while more:
        device = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(device)
        writer.end_page()
    writer.close()
    tmp.write_bytes(buffer.getvalue())
    os.replace(tmp, output)
    return output
